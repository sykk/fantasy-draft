// Tiers follow real ADP gaps: within a position, a new tier starts when the
// market leaves a meaningful gap between back-to-back players (or a tier
// gets too crowded to be one "cluster").
const MAX_TIER_SIZE: Record<Position, number> = { QB: 5, TE: 5, RB: 6, WR: 6 };

function computeTiers(): Map<number, number> {
  const tiers = new Map<number, number>(); // seed index -> tier
  const byPos = new Map<Position, number[]>();
  SEED.forEach(([, pos], i) => {
    if (!byPos.has(pos)) byPos.set(pos, []);
    byPos.get(pos)!.push(i);
  });
  for (const [pos, indices] of byPos) {
    let tier = 1;
    let sizeInTier = 0;
    let prevAdp = -Infinity;
    for (const i of indices) {
      const adp = i + 1;
      const gap = adp - prevAdp;
      const gapBreak = prevAdp > 0 && gap >= Math.max(4, prevAdp * 0.12);
      if ((gapBreak || sizeInTier >= MAX_TIER_SIZE[pos]) && tier < 8) {
        tier += 1;
        sizeInTier = 0;
      }
      tiers.set(i, tier);
      sizeInTier += 1;
      prevAdp = adp;
    }
  }
  return tiers;
}

function slugify(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

const TIERS = computeTiers();
const usedIds = new Set<string>();

export const PLAYERS: Player[] = SEED.map(([name, position, team, projPoints], i) => {
  let id = slugify(name);
  if (usedIds.has(id)) id = `${id}-${team.toLowerCase()}`;
  usedIds.add(id);
  return {
    id,
    name,
    position,
    team,
    byeWeek: TEAM_BYES[team] ?? 9,
    adp: i + 1,
    projPoints,
    tier: TIERS.get(i) ?? 8,
  };
});

export const PLAYER_BY_ID: Map<string, Player> = new Map(PLAYERS.map((p) => [p.id, p]));
